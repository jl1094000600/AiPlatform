CREATE TABLE IF NOT EXISTS ai_agent (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    tenant_id BIGINT NOT NULL DEFAULT 1,
    agent_code VARCHAR(64),
    agent_name VARCHAR(128),
    category VARCHAR(64),
    description VARCHAR(512),
    api_url VARCHAR(256),
    http_method VARCHAR(16),
    model_id BIGINT,
    model_code VARCHAR(128),
    request_schema CLOB,
    response_schema CLOB,
    status TINYINT DEFAULT 1,
    owner_id BIGINT,
    create_time TIMESTAMP,
    update_time TIMESTAMP,
    is_deleted TINYINT DEFAULT 0
);

CREATE TABLE IF NOT EXISTS ai_agent_heartbeat (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    tenant_id BIGINT NOT NULL DEFAULT 1,
    agent_id BIGINT,
    agent_code VARCHAR(64),
    instance_id VARCHAR(64),
    last_heartbeat TIMESTAMP,
    health_score INT,
    endpoint VARCHAR(256),
    status TINYINT DEFAULT 1,
    create_time TIMESTAMP,
    update_time TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ai_agent_graph_edge (
    id BIGINT NOT NULL AUTO_INCREMENT,
    tenant_id BIGINT NOT NULL DEFAULT 1,
    source_agent_id BIGINT NOT NULL,
    source_agent_code VARCHAR(64) NOT NULL,
    target_agent_id BIGINT NOT NULL,
    target_agent_code VARCHAR(64) NOT NULL,
    edge_type VARCHAR(32) NOT NULL DEFAULT 'ROUTE',
    trigger_intent VARCHAR(64) DEFAULT NULL,
    condition_expression VARCHAR(512) DEFAULT NULL,
    param_mapping CLOB DEFAULT NULL,
    timeout_seconds INT NOT NULL DEFAULT 30,
    retry_count INT NOT NULL DEFAULT 0,
    enabled TINYINT NOT NULL DEFAULT 1,
    suitability_level VARCHAR(16) DEFAULT NULL,
    suitability_score INT DEFAULT NULL,
    suitability_message VARCHAR(512) DEFAULT NULL,
    create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    is_deleted TINYINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_agent_graph_edge_pair (source_agent_id, target_agent_id, edge_type, trigger_intent),
    KEY idx_agent_graph_edge_source (source_agent_id, enabled),
    KEY idx_agent_graph_edge_target (target_agent_id, enabled),
    KEY idx_agent_graph_edge_codes (source_agent_code, target_agent_code)
);

CREATE TABLE IF NOT EXISTS ai_a2a_task (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    tenant_id BIGINT NOT NULL DEFAULT 1,
    task_id VARCHAR(64),
    session_id VARCHAR(64),
    workflow_id BIGINT,
    task_type VARCHAR(32),
    task_description CLOB,
    context CLOB,
    response_format VARCHAR(64),
    source_agent_id BIGINT,
    target_agent_id BIGINT,
    status VARCHAR(32),
    result CLOB,
    timeout INT,
    retry_count INT,
    start_time TIMESTAMP,
    end_time TIMESTAMP,
    error_message CLOB,
    create_time TIMESTAMP,
    update_time TIMESTAMP,
    is_deleted TINYINT DEFAULT 0
);

CREATE TABLE IF NOT EXISTS mon_call_record (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    tenant_id BIGINT NOT NULL DEFAULT 1,
    trace_id VARCHAR(64),
    agent_id BIGINT,
    agent_version VARCHAR(64),
    biz_module_id BIGINT,
    user_id BIGINT,
    username VARCHAR(128),
    model_id BIGINT,
    status_code INT,
    success TINYINT,
    duration_ms INT,
    input_tokens INT,
    output_tokens INT,
    total_tokens INT,
    request_time TIMESTAMP,
    response_time TIMESTAMP,
    error_message CLOB,
    request_params CLOB,
    response_result CLOB,
    create_time TIMESTAMP,
    update_time TIMESTAMP,
    is_deleted TINYINT DEFAULT 0
);
