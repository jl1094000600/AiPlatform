CREATE TABLE IF NOT EXISTS agent_run (
    id BIGINT NOT NULL AUTO_INCREMENT,
    tenant_id BIGINT NOT NULL,
    project_id BIGINT DEFAULT NULL,
    project_key VARCHAR(128) DEFAULT NULL,
    owner_user_id BIGINT DEFAULT NULL,
    business_type VARCHAR(64) NOT NULL,
    business_id VARCHAR(128) NOT NULL,
    agent_id BIGINT NOT NULL,
    agent_version_id BIGINT NOT NULL,
    definition_snapshot LONGTEXT NOT NULL,
    definition_hash VARCHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    status VARCHAR(32) NOT NULL,
    input_json LONGTEXT DEFAULT NULL,
    result_json LONGTEXT DEFAULT NULL,
    trace_id VARCHAR(96) DEFAULT NULL,
    memory_trace_id VARCHAR(96) DEFAULT NULL,
    loop_version VARCHAR(16) NOT NULL DEFAULT 'v1',
    context_window_tokens INT NOT NULL DEFAULT 0,
    context_used_tokens INT NOT NULL DEFAULT 0,
    compact_count INT NOT NULL DEFAULT 0,
    current_turn INT NOT NULL DEFAULT 0,
    stop_reason VARCHAR(64) DEFAULT NULL,
    max_steps INT NOT NULL DEFAULT 8,
    max_child_tasks INT NOT NULL DEFAULT 5,
    max_total_tokens INT NOT NULL DEFAULT 8000,
    total_tokens INT NOT NULL DEFAULT 0,
    error_message VARCHAR(2048) DEFAULT NULL,
    start_time DATETIME DEFAULT NULL,
    end_time DATETIME DEFAULT NULL,
    version INT NOT NULL DEFAULT 1,
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    is_deleted TINYINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_agent_run_idempotency (tenant_id, idempotency_key),
    KEY idx_agent_run_project_status (tenant_id, project_key, status, create_time),
    KEY idx_agent_run_owner_status (tenant_id, owner_user_id, status, create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

